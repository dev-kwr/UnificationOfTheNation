#!/bin/sh
# ============================================
# 全体マップ画像を Codex CLI の組み込み画像生成(imagegen)で生成する。
# ChatGPT サブスクリプション内で動く＝OpenAI API の従量課金は不要。
#
# 必要:
#   - Codex CLI 0.147 以降 (npm i -g @openai/codex)
#   - ChatGPT アカウントでログイン済み (codex login)
#
# 使い方:
#   sh tools/generate-worldmap-codex.sh
#
# 生成後、ノード位置が絵とずれていたら js/stageSelect.js の
# WORLD_MAP_NODES の u,v を微調整する(map_generation_prompt.md 参照)。
# プロンプトの正本は map_generation_prompt.md。変えるときは両方直すこと。
# ============================================
set -e
cd "$(dirname "$0")/.."

codex exec -s workspace-write -C "$PWD" "組み込みの画像生成ツール(imagegen)で次の画像を1枚、サイズ1536x1024(横長)で生成し、images/world_map.png として保存してください(既存ファイルは上書きしてよい)。他のファイルは一切変更しないこと。

画像の内容:
和風ゲームのステージセレクト用「全体マップ」。
夜の日本を描いた絵巻風の古地図。和紙の質感、墨の輪郭線、藍色基調に金のアクセント、落ち着いた水彩。
一本の街道が左下から右上へ蛇行し、途中に次のランドマークを配置:
(1) 左下: 月明かりの竹林 (2) その先: 茅葺き屋根の宿場町 (3) 中央左上: 杉の峠道
(4) 中央右: 瓦屋根の城下町 (5) その上: 石垣と城門 (6) 右上: 山上の天守閣、背後に大きな満月。
脇道が2本: 竹林と峠の間から下がった先に小さな小判蔵と鳥居、峠の上に滝のそばの道場。
文字・ラベル・枠・UIは一切描かない。画面の上下15%は空や霞だけにして重要な要素を置かない。
ゲームUIを上に重ねるため、全体のコントラストは控えめに。"

echo "[worldmap] 完了。ゲームを再読み込みすると反映されます。"
