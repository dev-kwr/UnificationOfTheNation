#!/bin/sh
# ============================================
# 全体マップ画像を Codex CLI の組み込み画像生成(imagegen)で生成する。
# ChatGPT サブスクリプション内で動く＝OpenAI API の従量課金は不要。
#
# 必要:
#   - Codex CLI 0.147 以降 (npm i -g @openai/codex)
#   - ChatGPT アカウントでログイン済み (codex login)
#
# 使い方:
#   sh tools/generate-worldmap-codex.sh
#
# 生成後、ノード位置が絵とずれていたら js/stageSelect.js の
# WORLD_MAP_NODES / WORLD_MAP_ROUTE の u,v を微調整する(map_generation_prompt.md 参照)。
# プロンプトの正本は map_generation_prompt.md。変えるときは両方直すこと。
# ============================================
set -e
cd "$(dirname "$0")/.."

codex exec -s workspace-write -C "$PWD" "組み込みの画像生成ツール(imagegen)で次の画像を1枚、サイズ1536x1024(横長)で生成し、images/world_map.png として保存してください(既存ファイルは上書き)。他のファイルは一切変更しないこと。

画像の内容:
和風ゲームのステージセレクト用「全体マップ」。夜の日本を描いた絵巻風の古地図。
和紙の質感、墨の輪郭線、藍色基調に金のアクセント、落ち着いた水彩。

【最重要・道の描き方】
道は「一本の街道」だけ。左下から右上まで途切れず一本でつながり、S字に蛇行しながら
次の順に通る: (1)月明かりの竹林 → (2)茅葺き屋根の宿場町 → (3)杉と滝の峠道 → (4)城下町。
本道以外の道路は描かない。道同士の交差・環状路・並行する別の道・網目状の小道は禁止。
例外は短い「行き止まりの脇道」を2本だけ:
(a) 宿場町と峠の間から下へ折れ、小さな小判蔵と鳥居で終わる脇道
(b) 峠から上へ折れ、滝のそばの道場で終わる脇道

【最重要・城下町と城の関係】
画面右側は「城郭都市」として一体に描く: 瓦屋根の城下町の家並みの奥(上)に石垣と城門があり、
城門のすぐ上の丘に天守閣がそびえ、天守の背後に大きな満月。
城下町・城門・天守は互いに離さず、町の中に城がある構図にする。
街道は城下町に入り、町並みを抜けて城門へ、門の先の短い坂で天守へと自然に続く。

文字・ラベル・枠・UIは一切描かない。画面の上下15%は空や霞だけにして重要な要素を置かない。
ゲームUIを上に重ねるため、全体のコントラストは控えめに。"

echo "[worldmap] 完了。ゲームを再読み込みすると反映されます。"
